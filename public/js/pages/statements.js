// ── Handlers ──────────────────────────────────────────────

function setupHandlers(container) {
  // Period selector
  let selectedPeriod = 'monthly';
  container.querySelector('#stmt-period-grid')?.addEventListener('click', e => {
    const chip = e.target.closest('.method-chip');
    if (!chip) return;
    container.querySelectorAll('#stmt-period-grid .method-chip').forEach(c => c.classList.remove('active'));
    chip.classList.add('active');
    selectedPeriod = chip.dataset.period;

    const customRange = container.querySelector('#stmt-custom-range');
    customRange?.classList.toggle('hidden', selectedPeriod !== 'custom');
  });

  // Generate button
  container.querySelector('#btn-gen-statement')?.addEventListener('click', async () => {
    const btn = container.querySelector('#btn-gen-statement');
    btn.classList.add('loading');
    btn.disabled = true;

    try {
      const { startDate, endDate, label } = getDateRange(selectedPeriod, container);
      const { generateStatement } = await import('../services/pdfService.js');
      await generateStatement(startDate, endDate, label);
      showToast('success', '✅ Statement downloaded successfully!');
      // Refresh the list
      await loadStatements(container);
    } catch (err) {
      showToast('error', 'PDF generation failed: ' + (err.message || 'Unknown error'));
      console.error('[Statements] PDF error:', err);
    } finally {
      btn.classList.remove('loading');
      btn.disabled = false;
    }
  });
}

// ── Load saved statements ─────────────────────────────────

async function loadStatements(container) {
  try {
    _allStatements = await getStatements();
    renderStatementsList(container, _allStatements);
  } catch {
    const el = container.querySelector('#statements-list');
    if (el) el.innerHTML = emptyState('⚠️', 'Could not load statements', t('errors.generic'));
  }
}

function renderStatementsList(container, list) {
  const el = container.querySelector('#statements-list');
  if (!el) return;

  if (!list || list.length === 0) {
    el.innerHTML = emptyState('📄', t('statements.empty'), t('statements.emptyDesc'));
    import('../i18n.js').then(({ rerender }) => rerender());
    return;
  }

  el.innerHTML = list.map(stmt => `
    <div class="console-panel animate-fade-in-up" style="padding:var(--space-4);">
      <div style="display:flex;align-items:center;justify-content:space-between;gap:var(--space-3);">
        <div style="display:flex;align-items:center;gap:var(--space-3);flex:1;min-width:0;">
          <div style="width:38px;height:38px;background:rgba(14,124,123,0.1);border-radius:var(--radius-md);
                      display:flex;align-items:center;justify-content:center;font-size:1.1rem;flex-shrink:0;color:var(--color-flow);">
            📄
          </div>
          <div style="min-width:0;">
            <div class="font-bold text-sm truncate">${escapeHtml(stmt.label || 'Statement')}</div>
            <div class="text-xs text-muted" style="margin-top:2px;">
              Generated ${formatDate(stmt.date || stmt.generatedAt)}
            </div>
            <div class="text-xs font-mono" style="margin-top:2px;color:var(--color-text-secondary);font-size:11px;">
              ${stmt.startDate ? `${formatDate(stmt.startDate)} → ${formatDate(stmt.endDate)}` : ''}
            </div>
          </div>
        </div>
        <div style="display:flex;gap:var(--space-2);flex-shrink:0;">
          <button class="btn btn-icon btn-secondary btn-icon-sm" data-action="redownload"
                  data-stid="${stmt.id}" title="Re-download PDF" aria-label="Download">
            ${iconDownload()}
          </button>
        </div>
      </div>
    </div>
  `).join('');

  // Re-download handler
  el.querySelectorAll('[data-action="redownload"]').forEach(btn => {
    btn.addEventListener('click', async () => {
      const id = parseInt(btn.dataset.stid, 10);
      const stmt = _allStatements.find(s => s.id === id);
      if (!stmt) return;
      btn.classList.add('loading');
      try {
        const { generateStatement } = await import('../services/pdfService.js');
        await generateStatement(stmt.startDate, stmt.endDate, stmt.label);
        showToast('success', 'Statement re-downloaded!');
      } catch (err) {
        showToast('error', 'Download failed: ' + err.message);
      } finally {
        btn.classList.remove('loading');
      }
    });
  });
}

function getDateRange(period, container) {
  const now = new Date();
  const y = now.getFullYear();
  const m = now.getMonth();

  switch (period) {
    case 'monthly': {
      const start = new Date(y, m, 1).toISOString().split('T')[0];
      const end   = new Date(y, m + 1, 0).toISOString().split('T')[0];
      const label = now.toLocaleDateString('en-IN', { month: 'long', year: 'numeric' });
      return { startDate: start, endDate: end, label };
    }
    case '3month': {
      const start = new Date(y, m - 2, 1).toISOString().split('T')[0];
      const end   = new Date(y, m + 1, 0).toISOString().split('T')[0];
      return { startDate: start, endDate: end, label: 'Last 3 Months' };
    }
    case '6month': {
      const start = new Date(y, m - 5, 1).toISOString().split('T')[0];
      const end   = new Date(y, m + 1, 0).toISOString().split('T')[0];
      return { startDate: start, endDate: end, label: 'Last 6 Months' };
    }
    case 'annual': {
      const start = new Date(y, 0, 1).toISOString().split('T')[0];
      const end   = new Date(y, 11, 31).toISOString().split('T')[0];
      return { startDate: start, endDate: end, label: `Year ${y}` };
    }
    case 'custom': {
      const start = container.querySelector('#stmt-from')?.value || new Date(y, m - 1, 1).toISOString().split('T')[0];
      const end   = container.querySelector('#stmt-to')?.value   || now.toISOString().split('T')[0];
      return { startDate: start, endDate: end, label: `${formatDate(start)} – ${formatDate(end)}` };
    }
    default:
      return {
        startDate: new Date(y, m, 1).toISOString().split('T')[0],
        endDate:   now.toISOString().split('T')[0],
        label: 'Custom Statement',
      };
  }
}

function formatDate(iso) {
  if (!iso) return '';
  return new Date(iso).toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric' });
}

function escapeHtml(str) {
  if (!str) return '';
  return String(str).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function skeletons() {
  return [1, 2].map(() => `<div class="skeleton" style="height:64px;border-radius:var(--radius-md);margin-bottom:var(--space-2);"></div>`).join('');
}

function emptyState(icon, title, desc) {
  return `
    <div class="empty-state">
      <div class="empty-state-icon">${icon}</div>
      <div class="empty-state-title">${title}</div>
      <div class="empty-state-desc">${desc}</div>
    </div>
  `;
}

function showToast(type, message) {
  import('../app.js').then(m => m.showToast?.(type, message)).catch(() => {});
}

function iconDownload() {
  return `<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4"/><polyline points="7 10 12 15 17 10"/><line x1="12" y1="15" x2="12" y2="3"/></svg>`;
}
